const root = document.documentElement;
const langToggle = document.querySelector("[data-lang-toggle]");
const themeToggle = document.querySelector("[data-theme-toggle]");

function read(locale, path) {
  return path.split(".").reduce((data, key) => data && data[key], copy[locale]);
}

function setLanguage(locale) {
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const text = read(locale, node.dataset.i18n);
    if (text) node.textContent = text;
  });
  root.lang = locale === "pt" ? "pt-BR" : "en";
  document.title = locale === "pt" ? "Planne | Planeje eventos sem estresse" : "Planne | Plan events without stress";
  langToggle.textContent = locale === "pt" ? "English" : "Portugues";
  localStorage.setItem("plannelang", locale);
}

function setTheme(theme) {
  root.classList.toggle("dark", theme === "dark");
  themeToggle.textContent = theme === "dark" ? "☀" : "☾";
  localStorage.setItem("plannetheme", theme);
}

const storedTheme = localStorage.getItem("plannetheme");
const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;
setTheme(storedTheme || (prefersDark ? "dark" : "light"));
setLanguage(localStorage.getItem("plannelang") || "pt");

langToggle.addEventListener("click", () => setLanguage(localStorage.getItem("plannelang") === "en" ? "pt" : "en"));
themeToggle.addEventListener("click", () => setTheme(root.classList.contains("dark") ? "light" : "dark"));
